test('caller cancellation prevents all later ranked batches', async () => {
  const controller = new AbortController();
  const f = fixture(40,{},(call,calls)=>{
    if(call.endpoint==='search' && calls.filter(c=>c.endpoint==='search').length===3) controller.abort();
  });
  await assert.rejects(f.p.resolveGlobalNewReleaseSignals(f.signals,controller.signal),{name:'AbortError'});
  assert.equal(searchCalls(f).length,3);
  const pre = fixture(10); controller.abort();
  await assert.rejects(pre.p.resolveGlobalNewReleaseSignals(pre.signals,controller.signal),{name:'AbortError'});
  assert.equal(pre.calls.length,0);
});

test('provider failures stay isolated and exhaustion never supplies filler', async () => {
  const responses = {};
  for(let i=0;i<20;i++) responses[`search:Catalog Artist Release ${i} Official Video`] = new Error('Unavailable');
  const failed = fixture(20,responses);
  await assert.rejects(failed.p.resolveGlobalNewReleaseSignals(failed.signals),/Unavailable/);
  delete responses['search:Catalog Artist Release 19 Official Video'];
  const partial = fixture(20,responses);
  assert.deepEqual((await partial.p.resolveGlobalNewReleaseSignals(partial.signals)).map(e=>e.item.source.id),[id('c',19)]);
});

test('the 48-signal safety ceiling bounds requests even if an internal caller supplies a larger pool', async () => {
  const responses = {};
  for(let i=0;i<60;i++) responses[`player:${id('c',i)}`] = player(null,today());
  const f = fixture(60,responses);
  assert.deepEqual(await f.p.resolveGlobalNewReleaseSignals(f.signals),[]);
  assert.equal(searchCalls(f).length,48);
});

test('complete batches publish in rank order despite reversed HTTP completion', async () => {
  const f = fixture(5,{},async call=>{
    if(call.endpoint==='search') {
      const index=Number(call.body.query.match(/Release (\d+)/)[1]);
      await new Promise(resolve=>setTimeout(resolve, (5-index)*2));
    }
  });
  assert.deepEqual((await f.p.resolveGlobalNewReleaseSignals(f.signals)).map(e=>e.item.source.id),
    Array.from({length:5},(_,i)=>id('c',i)));
});

test('fixed markets and rank deduplication remain deterministic with the expanded safety window', () => {
  const f = fixture(60);
  const sections = items=>[{type:'tracks',items}];
  const markets = [{market:'US',sections:sections(f.signals.map(s=>s.item))},
    {market:'GB',sections:sections(f.signals.slice().reverse().map(s=>s.item))}];
  const first = f.p.rankGlobalNewReleaseSignals(markets);
  const second = f.p.rankGlobalNewReleaseSignals(markets);
  assert.equal(first.length,48);
  assert.deepEqual(first,second);
  assert.ok(first.every(s=>s.marketCount===2));
  assert.deepEqual(f.p.WAVEN_GLOBAL_DISCOVERY_MARKETS,['US','GB','KR','JP','IN','BR','MX','DE']);
});

