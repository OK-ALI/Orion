const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const ts = require('typescript');
const vm = require('node:vm');
const esbuild = require('esbuild');

const source = fs.readFileSync(path.join(__dirname, '../src/infrastructure/music/providers/newReleaseVerification.ts'), 'utf8');
const output = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText;
const moduleRecord = { exports: {} };
vm.runInNewContext(output, { module: moduleRecord, exports: moduleRecord.exports, Date });
const { canonicalCatalogReleaseDate, releaseTitleSimilarity, releaseTimeCompatible } = moduleRecord.exports;

function catalogPlayer(releasedOn, publishedOn = releasedOn) {
  return {
    videoDetails: { shortDescription: `Provided to YouTube by Example Label\n\nSong · Artist\n\nReleased on: ${releasedOn}\n\nAuto-generated by YouTube.` },
    microformat: { playerMicroformatRenderer: { publishDate: publishedOn } },
  };
}

test('release parts preserve identity while punctuation and part spelling normalize', () => {
  assert.equal(releaseTitleSimilarity('Protocol Pt. 3', 'Protocol'), 0);
  assert.equal(releaseTitleSimilarity('Protocol Pt. 3', 'protocol pt 3'), 1);
  assert.equal(releaseTitleSimilarity('Protocol Pt. 3', 'Protocol Part III'), 1);
  assert.equal(releaseTitleSimilarity('Protocol Pt. 3', 'Protocol Pt. 2'), 0);
  assert.equal(releaseTitleSimilarity('Song Part II', 'Song'), 0);
  assert.equal(releaseTitleSimilarity('Song Vol. II', 'Song Volume 2'), 1);
  assert.equal(releaseTitleSimilarity('Song Chapter III', 'Song Chapter 3'), 1);
  assert.equal(releaseTitleSimilarity('Song Remastered', 'Song Remaster'), 1);
});

test('edition and recording qualifiers cannot be dropped or added', () => {
  for (const suffix of ['Remix', 'Live Version', 'Acoustic', '2026 Remaster', 'Deluxe', 'Deluxe Edition', 'Extended Mix', 'Radio Edit', 'Reprise', 'Demo', 'Instrumental', 'sped up', 'slowed', 'Edition', 'Version']) {
    assert.equal(releaseTitleSimilarity(`Song (${suffix})`, 'Song'), 0, suffix);
    assert.equal(releaseTitleSimilarity('Song', `Song (${suffix})`), 0, suffix);
  }
  assert.equal(releaseTitleSimilarity('Song Remix', 'Song Acoustic'), 0);
});

test('formatting and video wrappers do not change release identity', () => {
  assert.equal(releaseTitleSimilarity('SONG! [Official Video]', 'song'), 1);
  assert.equal(releaseTitleSimilarity('It’s Over', "it's over"), 1);
  assert.equal(releaseTitleSimilarity('Fue Solo Ficción (Video Oficial)', 'Fue Solo Ficción'), 1);
  assert.equal(releaseTitleSimilarity('Artist - Song (Video Oficial)', 'Song'), 0);
  assert.equal(releaseTitleSimilarity('One Two Three', 'Three Two One'), 0.96);
});

test('extra base words and trailing numbers cannot impersonate a different release', () => {
  assert.equal(releaseTitleSimilarity('MEGA FUNK RELIQUIAS', 'MEGA FUNK RELIQUIAS 6'), 0);
  assert.equal(releaseTitleSimilarity('Song', 'Song 2026'), 0);
  assert.equal(releaseTitleSimilarity('One Two Three Four', 'One Two Three Four Five'), 0);
});

test('fresh signal cannot promote an old canonical recording', () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  assert.equal(releaseTimeCompatible('2026-09-19', '2021-11-12', now), false);
  assert.equal(releaseTimeCompatible('2026-09-19', '2026-05-28', now), false);
});

test('current matching canonical audio qualifies across a normal video lag', () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  assert.equal(releaseTimeCompatible('2026-09-19', '2026-09-10', now), true);
});

test('unknown dates, future dates, and old signals fail closed', () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  assert.equal(releaseTimeCompatible('2026-09-19', '', now), false);
  assert.equal(releaseTimeCompatible('', '2026-09-19', now), false);
  assert.equal(releaseTimeCompatible('2026-09-19', '2027-01-01', now), false);
  assert.equal(releaseTimeCompatible('2026-05-01', '2026-09-19', now), false);
});

test('temporal ceilings are explicit and do not silently become a 14-day product rule', () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const daysAgo = (days) => new Date(now - days * 86_400_000).toISOString();
  assert.equal(releaseTimeCompatible(daysAgo(60), daysAgo(60), now), true);
  assert.equal(releaseTimeCompatible(daysAgo(61), daysAgo(61), now), false);
  assert.equal(releaseTimeCompatible(daysAgo(1), daysAgo(46), now), true);
  assert.equal(releaseTimeCompatible(daysAgo(1), daysAgo(47), now), false);
});

test('an explicit provider-generated catalog release date is stronger than upload metadata', () => {
  assert.equal(canonicalCatalogReleaseDate(catalogPlayer('2026-09-10').videoDetails.shortDescription), '2026-09-10');
  assert.equal(canonicalCatalogReleaseDate('Song\nReleased on: 2026-09-10'), null);
  assert.equal(canonicalCatalogReleaseDate('Provided to YouTube by Label\nReleased on: 2026-09-10'), null);
  assert.equal(canonicalCatalogReleaseDate(catalogPlayer('2026-02-31').videoDetails.shortDescription), null);
  assert.equal(canonicalCatalogReleaseDate(''), null);
});

const providerFile = path.join(__dirname, '../src/infrastructure/music/providers/youtubeMusicMetadata.ts');
const providerSource = fs.readFileSync(providerFile, 'utf8') +
  '\nexport { releaseSignalCandidateScore, verifyCanonicalReleaseTime, rememberCatalogArtistHint, rankGlobalNewReleaseSignals, resolveNewReleaseSignal, resolveGlobalNewReleaseSignals };';
const providerBundle = esbuild.buildSync({
  stdin: {
    contents: providerSource,
    resolveDir: path.dirname(providerFile),
    sourcefile: providerFile,
    loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'cjs',
  write: false,
}).outputFiles[0].text;

function providerWithResponses(responses) {
  const moduleRecord = { exports: {} };
  const calls = [];
  const fetch = async (url, options) => {
    if (options?.signal?.aborted) {
      const error = new Error('Aborted');
      error.name = 'AbortError';
      throw error;
    }
    if (!options?.body) return { ok: true, status: 200, text: async () => '' };
    const endpoint = String(url).split('/youtubei/v1/')[1].split('?')[0];
    const body = JSON.parse(options.body);
    calls.push({ endpoint, body });
    const payload = (endpoint === 'search' ? responses[`search:${body.query}`] : null) ||
      responses[`${endpoint}:${body.videoId || body.browseId}`] || {};
    if (payload instanceof Error) throw payload;
    return { ok: true, status: 200, json: async () => payload };
  };
  vm.runInNewContext(providerBundle, {
    module: moduleRecord, exports: moduleRecord.exports, fetch, Date, console,
  });
  return { provider: moduleRecord.exports, calls };
}

function musicTrack(title, artistName, id) {
  return { title, artistName, id: `ytmusic:${id}`, providerTrackId: id,
    source: { provider: 'ytmusic-metadata', id } };
}

function catalogSearchPayload(title, artist, id, artistId = 'UCartistOne') {
  return { contents: [{ musicResponsiveListItemRenderer: {
    flexColumns: [
      { musicResponsiveListItemFlexColumnRenderer: { text: { runs: [{ text: title }] } } },
      { musicResponsiveListItemFlexColumnRenderer: { text: { runs: [{ text: 'Song' }, { text: ' • ' }, {
        text: artist, navigationEndpoint: { browseEndpoint: { browseId: artistId,
          browseEndpointContextSupportedConfigs: { browseEndpointContextMusicConfig: {
            pageType: 'MUSIC_PAGE_TYPE_ARTIST',
          } },
        } },
      }] } } },
    ],
    playlistItemData: { videoId: id },
  } }] };
}

test('candidate scoring rejects unrelated versions, artists and video wrappers', () => {
  const { provider } = providerWithResponses({});
  const signal = musicTrack('Protocol Pt. 3', 'Skeng', 'aaaaaaaaaaa');
  assert.equal(provider.releaseSignalCandidateScore(signal, musicTrack('Protocol', 'Skeng', 'bbbbbbbbbbb')), -1);
  assert.equal(provider.releaseSignalCandidateScore(signal, musicTrack('Protocol Pt. 3', 'Other Artist', 'bbbbbbbbbbb')), -1);
  assert.equal(provider.releaseSignalCandidateScore(signal, musicTrack('Protocol Pt. 3 Official Video', 'Skeng', 'bbbbbbbbbbb')), -1);
  assert.ok(provider.releaseSignalCandidateScore(signal, musicTrack('Protocol Pt 3', 'Skeng', 'bbbbbbbbbbb')) > 0);
});

test('same display-name artists with different provider identities cannot match', () => {
  const { provider } = providerWithResponses({});
  const signal = musicTrack('Song', 'Same Name', 'aaaaaaaaaaa');
  const candidate = musicTrack('Song', 'Same Name', 'bbbbbbbbbbb');
  const runs = (id) => [{ text: 'Same Name', navigationEndpoint: { browseEndpoint: {
    browseId: id, browseEndpointContextSupportedConfigs: { browseEndpointContextMusicConfig: {
      pageType: 'MUSIC_PAGE_TYPE_ARTIST',
    } },
  } } }];
  provider.rememberCatalogArtistHint(signal, runs('UCartistOne'));
  provider.rememberCatalogArtistHint(candidate, runs('UCartistTwo'));
  assert.equal(provider.releaseSignalCandidateScore(signal, candidate), -1);
  const unlinked = musicTrack('Song', 'Same Name', 'ccccccccccc');
  assert.equal(provider.releaseSignalCandidateScore(signal, unlinked), -1);
});

test('OMV freshness rows are signals and resolve only to a different canonical catalog ID', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const candidateId = 'bbbbbbbbbbb';
  const { provider } = providerWithResponses({
    'player:aaaaaaaaaaa': { microformat: { playerMicroformatRenderer: { publishDate: '2026-09-19' } } },
    [`player:${candidateId}`]: catalogPlayer('2026-09-10'),
    'search:undefined': catalogSearchPayload('Song', 'Artist', candidateId),
  });
  const omv = musicTrack('Song Official Video', 'Artist', 'aaaaaaaaaaa');
  provider.rememberCatalogArtistHint(omv, [{ text: 'Artist', navigationEndpoint: {
    browseEndpoint: { browseId: 'UCartistOne',
      browseEndpointContextSupportedConfigs: { browseEndpointContextMusicConfig: {
        pageType: 'MUSIC_PAGE_TYPE_ARTIST',
      } },
    },
  } }]);
  const signals = provider.rankGlobalNewReleaseSignals([{ market: 'US', sections: [{
    type: 'tracks', items: [omv],
  }] }]);
  assert.equal(signals.length, 1);
  const resolved = await provider.resolveNewReleaseSignal(signals[0], now);
  assert.equal(resolved?.type, 'tracks');
  assert.equal(resolved?.item?.source.id, candidateId);
  assert.notEqual(resolved?.item?.source.id, omv.source.id);
});

test('one failed signal does not turn into filler or prevent a later valid signal', async () => {
  const instance = providerWithResponses({
    'search:Artist Broken Official Video': new Error('Search unavailable'),
    'search:Artist Song Official Video': catalogSearchPayload('Song', 'Artist', 'bbbbbbbbbbb'),
    'player:ccccccccccc': { microformat: { playerMicroformatRenderer: { publishDate: new Date().toISOString() } } },
    'player:bbbbbbbbbbb': catalogPlayer(new Date().toISOString().slice(0, 10)),
  });
  const broken = musicTrack('Broken Official Video', 'Artist', 'aaaaaaaaaaa');
  const valid = musicTrack('Song Official Video', 'Artist', 'ccccccccccc');
  instance.provider.rememberCatalogArtistHint(valid, [{ text: 'Artist', navigationEndpoint: {
    browseEndpoint: { browseId: 'UCartistOne',
      browseEndpointContextSupportedConfigs: { browseEndpointContextMusicConfig: {
        pageType: 'MUSIC_PAGE_TYPE_ARTIST',
      } },
    },
  } }]);
  const result = await instance.provider.resolveGlobalNewReleaseSignals([
    { item: broken, market: 'US', bestRank: 0, firstMarketIndex: 0, marketCount: 1 },
    { item: valid, market: 'US', bestRank: 1, firstMarketIndex: 0, marketCount: 1 },
  ]);
  assert.equal(result.length, 1);
  assert.equal(result[0].item.source.id, 'bbbbbbbbbbb');
});

test('canonical track player date is required before publishing', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const candidate = { type: 'tracks', item: musicTrack('Song', 'Artist', 'bbbbbbbbbbb') };
  const old = providerWithResponses({
    'player:bbbbbbbbbbb': catalogPlayer('2026-05-28'),
  });
  assert.equal(await old.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US'), false);
  const recent = providerWithResponses({
    'player:bbbbbbbbbbb': catalogPlayer('2026-09-10'),
  });
  assert.equal(await recent.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US'), true);
  assert.equal(recent.calls.filter((call) => call.endpoint === 'player').length, 1);
  assert.equal(recent.calls.find((call) => call.endpoint === 'player').body.context.client.clientName, 'WEB');
});

test('weak upload timing or conflicting provider dates cannot establish canonical recency', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const candidate = { type: 'tracks', item: musicTrack('Song', 'Artist', 'bbbbbbbbbbb') };
  const uploadOnly = providerWithResponses({
    'player:bbbbbbbbbbb': { microformat: { microformatDataRenderer: { publishDate: '2026-09-10' } } },
  });
  assert.equal(await uploadOnly.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US'), false);
  const conflicting = providerWithResponses({
    'player:bbbbbbbbbbb': catalogPlayer('2021-11-12', '2026-09-10'),
  });
  assert.equal(await conflicting.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US'), false);
});

test('recency verification shares one in-flight request per canonical entity', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const candidate = { type: 'tracks', item: musicTrack('Song', 'Artist', 'bbbbbbbbbbb') };
  const instance = providerWithResponses({ 'player:bbbbbbbbbbb': catalogPlayer('2026-09-10') });
  const cache = new Map();
  const decisions = await Promise.all([
    instance.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US', undefined, cache),
    instance.provider.verifyCanonicalReleaseTime('2026-09-19', candidate, now, 'US', undefined, cache),
  ]);
  assert.deepEqual(decisions, [true, true]);
  assert.equal(instance.calls.filter((call) => call.endpoint === 'player').length, 1);
});

test('a currently released new remaster can qualify while its original cannot', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const { provider } = providerWithResponses({
    'player:bbbbbbbbbbb': catalogPlayer('2026-09-10'),
    'player:ccccccccccc': catalogPlayer('2021-11-12'),
  });
  const signal = musicTrack('Song (2026 Remaster)', 'Artist', 'aaaaaaaaaaa');
  const newVersion = musicTrack('Song - 2026 Remastered', 'Artist', 'bbbbbbbbbbb');
  const original = musicTrack('Song', 'Artist', 'ccccccccccc');
  assert.ok(provider.releaseSignalCandidateScore(signal, newVersion) > 0);
  assert.equal(provider.releaseSignalCandidateScore(signal, original), -1);
  assert.equal(await provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'tracks', item: newVersion }, now, 'US'), true);
  assert.equal(await provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'tracks', item: original }, now, 'US'), false);
});

test('a canonical Single uses its own browse year and audio date', async () => {
  const now = Date.parse('2026-09-23T12:00:00Z');
  const item = { title: 'Song', artistName: 'Artist', id: 'ytmusic-album:MPRErecent',
    source: { provider: 'ytmusic-metadata', id: 'MPRErecent' } };
  const album = (year) => ({ contents: { twoColumnBrowseResultsRenderer: {
    tabs: [{ tabRenderer: { content: { sectionListRenderer: { contents: [{ musicResponsiveHeaderRenderer: {
      subtitle: { runs: [{ text: 'Single' }, { text: ' • ' }, { text: String(year) }] },
    } }] } } } }],
    secondaryContents: { sectionListRenderer: { contents: [{ musicShelfRenderer: { contents: [
      { musicResponsiveListItemRenderer: { playlistItemData: { videoId: 'ccccccccccc' } } },
    ] } }] } },
  } } });
  const recent = providerWithResponses({
    'browse:MPRErecent': album(2026),
    'player:ccccccccccc': catalogPlayer('2026-09-12'),
  });
  assert.equal(await recent.provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'albums', item }, now, 'US'), true);
  const stale = providerWithResponses({ 'browse:MPRErecent': album(2021) });
  assert.equal(await stale.provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'albums', item }, now, 'US'), false);
  assert.equal(stale.calls.filter((call) => call.endpoint === 'player').length, 0);
  const weakOnly = providerWithResponses({
    'browse:MPRErecent': album(2026),
    'player:ccccccccccc': { microformat: { playerMicroformatRenderer: { publishDate: '2026-09-12' } } },
  });
  assert.equal(await weakOnly.provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'albums', item }, now, 'US'), false);
  const conflicting = providerWithResponses({
    'browse:MPRErecent': album(2026),
    'player:ccccccccccc': catalogPlayer('2025-12-30'),
  });
  assert.equal(await conflicting.provider.verifyCanonicalReleaseTime('2026-01-08', { type: 'albums', item }, Date.parse('2026-01-10T12:00:00Z'), 'US'), false);
  const failedBrowse = providerWithResponses({ 'browse:MPRErecent': new Error('Provider failed') });
  await assert.rejects(failedBrowse.provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'albums', item }, now, 'US'));
  const cancelled = providerWithResponses({});
  const controller = new AbortController();
  controller.abort();
  await assert.rejects(cancelled.provider.verifyCanonicalReleaseTime('2026-09-19', { type: 'albums', item }, now, 'US', controller.signal), { name: 'AbortError' });
});
