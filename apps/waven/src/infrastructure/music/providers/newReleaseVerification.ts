/** Identity and time checks for converting a current video signal into catalog music. */
// Safety ceilings for a provider New Releases signal, applied only after the
// canonical catalog supplies an explicit label release date. They allow a
// delayed video while excluding old recordings promoted by a current upload.
export const NEW_RELEASE_MAX_AGE_DAYS = 60;
export const NEW_RELEASE_MAX_SIGNAL_LAG_DAYS = 45;

export function releaseTitleIdentity(value: unknown): { base: string; qualifiers: string } {
  let text = String(value || '').normalize('NFKD').toLowerCase()
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\[(](?:official\s+)?(?:music\s+)?video[\])]/gu, ' ')
    .replace(/[\[(](?:video\s+oficial|clip\s+officiel|offizielles?\s+(?:musik)?video)[\])]/gu, ' ')
    .replace(/[\[(](?:official\s+)?audio[\])]/gu, ' ')
    .replace(/[\[(](?:lyric(?:s)?\s+video|visuali[sz]er)[\])]/gu, ' ')
    .replace(/[\[(](?:feat\.?|ft\.?)\s+[^\])]+[\])]/gu, ' ')
    .replace(/\bvideo\s+oficial\b|\bclip\s+officiel\b|\boffizielles?\s+(?:musik)?video\b|\b(?:official\s+)?music\s+video\b|\b(?:official\s+)?video\b/gu, ' ')
    .replace(/\bpt\.?\s*(?:iii|3)\b/gu, 'part 3')
    .replace(/\bpt\.?\s*(?:ii|2)\b/gu, 'part 2')
    .replace(/\bpt\.?\s*(?:i|1)\b/gu, 'part 1')
    .replace(/\bpart\s+iii\b/gu, 'part 3')
    .replace(/\bpart\s+ii\b/gu, 'part 2')
    .replace(/\bpart\s+i\b/gu, 'part 1')
    .replace(/\b(vol|volume|chapter)\.?\s+iii\b/gu, '$1 3')
    .replace(/\b(vol|volume|chapter)\.?\s+ii\b/gu, '$1 2')
    .replace(/\b(vol|volume|chapter)\.?\s+i\b/gu, '$1 1')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();

  // These tokens describe a recording or edition. Their presence and value
  // must agree on both sides; otherwise a base song can impersonate a release.
  const qualifiers: string[] = [];
  const pattern = /\b(?:part\s+\d+|(?:vol|volume|chapter)\s+\d+|\d{4}\s+remaster(?:ed)?|re\s+recorded|remaster(?:ed)?|extended\s+mix|radio\s+edit|remix|acoustic|live|version|deluxe|reprise|demo|instrumental|sped\s+up|slowed|edition|edit)\b/gu;
  text = text.replace(pattern, (match) => {
    qualifiers.push(match.replace(/\s+/g, ' ')
      .replace(/^volume\s+/, 'vol ')
      .replace(/remastered$/, 'remaster')
      .replace(/^re recorded$/, 'rerecorded'));
    return ' ';
  }).replace(/\s+/g, ' ').trim();
  const trailingNumber = text.match(/(?:^|\s)(\d{1,4})$/);
  if (trailingNumber) {
    qualifiers.push(`number ${trailingNumber[1]}`);
    text = text.slice(0, trailingNumber.index).trim();
  }
  return { base: text, qualifiers: qualifiers.sort().join('|') };
}

export function releaseTitleSimilarity(signal: unknown, candidate: unknown): number {
  const left = releaseTitleIdentity(signal);
  const right = releaseTitleIdentity(candidate);
  if (!left.base || !right.base || left.qualifiers !== right.qualifiers) return 0;
  if (left.base === right.base) return 1;
  // Token order can vary in provider presentation; missing or additional
  // words cannot establish the same release identity.
  return left.base.split(' ').sort().join(' ') === right.base.split(' ').sort().join(' ')
    ? 0.96
    : 0;
}

export function verifiedReleaseDate(value: unknown): number | null {
  const text = String(value || '');
  if (!/^\d{4}-\d{2}-\d{2}(?:T|$)/.test(text)) return null;
  const calendarDay = text.slice(0, 10);
  const midnight = new Date(`${calendarDay}T00:00:00Z`);
  if (!Number.isFinite(midnight.getTime()) || midnight.toISOString().slice(0, 10) !== calendarDay) {
    return null;
  }
  const time = Date.parse(text);
  return Number.isFinite(time) ? time : null;
}

/** Only the provider-generated catalog attribution is release-date evidence. */
export function canonicalCatalogReleaseDate(description: unknown): string | null {
  const text = String(description || '');
  if (!/^Provided to YouTube by\s+.+/m.test(text) ||
      !/^Auto-generated by YouTube\.\s*$/m.test(text)) return null;
  const dates = [...text.matchAll(/^Released on:\s*(\d{4}-\d{2}-\d{2})\s*$/gm)];
  if (dates.length !== 1 || verifiedReleaseDate(dates[0][1]) === null) return null;
  return dates[0][1];
}

export function releaseTimeCompatible(
  signalDate: unknown,
  canonicalDate: unknown,
  observedAt: number,
): boolean {
  const signal = verifiedReleaseDate(signalDate);
  const canonical = verifiedReleaseDate(canonicalDate);
  if (signal === null || canonical === null || !Number.isFinite(observedAt)) return false;
  const day = 86_400_000;
  // A release video can trail the catalog audio. Neither a months-old audio
  // record nor a future-dated provider record qualifies as a current release.
  return signal <= observedAt + day && signal >= observedAt - NEW_RELEASE_MAX_AGE_DAYS * day &&
    canonical <= observedAt + day && canonical >= observedAt - NEW_RELEASE_MAX_AGE_DAYS * day &&
    Math.abs(signal - canonical) <= NEW_RELEASE_MAX_SIGNAL_LAG_DAYS * day;
}
